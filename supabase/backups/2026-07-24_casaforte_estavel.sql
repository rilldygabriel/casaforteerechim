create table if not exists public.visitantes (
  id                     bigint generated by default as identity primary key,
  nome                   text not null,
  telefone               text not null,
  cidade                 text not null,
  bairro                 text not null,
  acompanhamento         boolean not null default false,
  convidado_por          text,
  igreja_anterior        text,
  passo_fe               text not null,
  mensagem_pastor        boolean not null default false,
  experiencia_culto      text not null,
  voltar_culto           text not null,
  data_visita            date not null default current_date,
  status_acompanhamento  text not null default 'novo',
  created_at             timestamptz not null default now()
);

-- Sequence do id: criada e vinculada automaticamente pelo
-- "GENERATED BY DEFAULT AS IDENTITY" acima (public.visitantes_id_seq),
-- OWNED BY public.visitantes.id. Nenhum comando manual de CREATE SEQUENCE
-- é necessário.

-- CHECK constraints
alter table public.visitantes
  drop constraint if exists visitantes_passo_fe_check;
alter table public.visitantes
  add constraint visitantes_passo_fe_check
  check (passo_fe = any (array['aceitei_jesus','batizado','caminhada_longa','conhecendo']));

alter table public.visitantes
  drop constraint if exists visitantes_experiencia_culto_check;
alter table public.visitantes
  add constraint visitantes_experiencia_culto_check
  check (experiencia_culto = any (array['ruim','boa','ótima']));

alter table public.visitantes
  drop constraint if exists visitantes_voltar_culto_check;
alter table public.visitantes
  add constraint visitantes_voltar_culto_check
  check (voltar_culto = any (array['Sim, estarei no próximo culto','Não, fui só visitar']));

alter table public.visitantes
  drop constraint if exists visitantes_status_acompanhamento_check;
alter table public.visitantes
  add constraint visitantes_status_acompanhamento_check
  check (status_acompanhamento = any (array['novo','em_contato','acompanhado','concluido']));

-- Índices: nenhum índice adicional além do índice único do primary key
-- (visitantes_pkey), criado automaticamente pelo PRIMARY KEY acima.


-- ----------------------------------------------------------------------------
-- 3) TABELA: public.pedidos_oracao
-- ----------------------------------------------------------------------------
create table if not exists public.pedidos_oracao (
  id                bigint generated by default as identity primary key,
  nome              text not null,
  telefone          text not null,
  categoria         text not null,
  pedido            text not null,
  deseja_contato    boolean not null default false,
  urgente           boolean not null default false,
  status            text not null default 'novo',
  responsavel       text,
  observacoes       text,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

-- Sequence do id: criada e vinculada automaticamente pelo
-- "GENERATED BY DEFAULT AS IDENTITY" acima (public.pedidos_oracao_id_seq),
-- OWNED BY public.pedidos_oracao.id.

-- CHECK constraints
alter table public.pedidos_oracao
  drop constraint if exists pedidos_oracao_categoria_check;
alter table public.pedidos_oracao
  add constraint pedidos_oracao_categoria_check
  check (categoria = any (array['saude','familia','vida_espiritual','casamento','financeiro','ansiedade_emocional','outro']));

alter table public.pedidos_oracao
  drop constraint if exists pedidos_oracao_status_check;
alter table public.pedidos_oracao
  add constraint pedidos_oracao_status_check
  check (status = any (array['novo','em_oracao','em_contato','concluido']));

alter table public.pedidos_oracao
  drop constraint if exists pedidos_oracao_pedido_check;
alter table public.pedidos_oracao
  add constraint pedidos_oracao_pedido_check
  check (length(trim(pedido)) >= 5 and length(trim(pedido)) <= 5000);

alter table public.pedidos_oracao
  drop constraint if exists pedidos_oracao_nome_check;
alter table public.pedidos_oracao
  add constraint pedidos_oracao_nome_check
  check (length(trim(nome)) >= 3);

alter table public.pedidos_oracao
  drop constraint if exists pedidos_oracao_telefone_check;
alter table public.pedidos_oracao
  add constraint pedidos_oracao_telefone_check
  check (length(trim(telefone)) >= 8);

-- Índices: nenhum índice adicional além do índice único do primary key
-- (pedidos_oracao_pkey), criado automaticamente pelo PRIMARY KEY acima.


-- ----------------------------------------------------------------------------
-- 4) FUNÇÃO E TRIGGER — updated_at de pedidos_oracao
-- ----------------------------------------------------------------------------
create or replace function public.set_pedidos_oracao_updated_at()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists pedidos_oracao_set_updated_at on public.pedidos_oracao;
create trigger pedidos_oracao_set_updated_at
  before update on public.pedidos_oracao
  for each row
  execute function public.set_pedidos_oracao_updated_at();

-- public.visitantes não possui função nem trigger próprios.


