-- ----------------------------------------------------------------------------
-- 6) POLICIES
-- ----------------------------------------------------------------------------
drop policy if exists visitantes_anon_insert on public.visitantes;
create policy visitantes_anon_insert
  on public.visitantes
  for insert
  to anon
  with check (
    length(trim(nome)) >= 3
    and length(trim(telefone)) >= 8
    and length(trim(cidade)) >= 2
    and length(trim(bairro)) >= 2
  );

drop policy if exists pedidos_oracao_anon_insert on public.pedidos_oracao;
create policy pedidos_oracao_anon_insert
  on public.pedidos_oracao
  for insert
  to anon
  with check (
    length(trim(nome)) >= 3
    and length(trim(telefone)) >= 8
    and length(trim(pedido)) between 5 and 5000
  );

-- Nenhuma política de SELECT, UPDATE ou DELETE existe para o público em
-- nenhuma das duas tabelas. Nenhuma política administrativa foi criada
-- ainda (reservado para quando o painel admin for construído, usando
-- member_profiles.is_admin = true).


-- ----------------------------------------------------------------------------
-- 7) GRANTS / REVOKES — anon, authenticated, service_role
-- ----------------------------------------------------------------------------
-- Privilégio mínimo: público (anon) só pode INSERT. authenticated não tem
-- nenhum privilégio de tabela hoje (nenhuma policy/uso administrativo ainda
-- construído). service_role mantém acesso total (papel interno do Supabase).

revoke all on public.visitantes from anon, authenticated;
grant insert on public.visitantes to anon;
grant usage on sequence public.visitantes_id_seq to anon;

revoke all on public.pedidos_oracao from anon, authenticated;
grant insert on public.pedidos_oracao to anon;
grant usage on sequence public.pedidos_oracao_id_seq to anon;

-- service_role mantém os privilégios padrão do Supabase (SELECT, INSERT,
-- UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER) em ambas as tabelas —
-- não é necessário GRANT explícito, pois já vem do papel interno do
-- projeto Supabase.

-- Observação de fidelidade: por padrão de privilégios do schema public do
-- Supabase, os papéis anon, authenticated e service_role já recebem USAGE
-- automático nas sequences de novas tabelas (default privileges do
-- projeto). O GRANT explícito de USAGE para anon acima é redundante com
-- esse padrão, mas foi mantido para deixar a intenção explícita e não
-- depender apenas do default do projeto.


